import path from "node:path";

import type { ExtractTablesWithRelations } from "drizzle-orm";
import { drizzle } from "drizzle-orm/node-postgres";
import { migrate as migrateNodePg } from "drizzle-orm/node-postgres/migrator";
import type { PgDatabase, PgQueryResultHKT, PgTransaction } from "drizzle-orm/pg-core";
import pg from "pg";

import * as schema from "./schema/index.js";

export type Schema = typeof schema;

/** Driver-agnostic Drizzle database: node-postgres in production, PGlite in tests. */
export type Database = PgDatabase<PgQueryResultHKT, Schema>;
export type Transaction = PgTransaction<
  PgQueryResultHKT,
  Schema,
  ExtractTablesWithRelations<Schema>
>;
/** Anything queries can run on: the database itself or an open transaction. */
export type Executor = Database | Transaction;

/** SQL migrations generated by drizzle-kit (packages/db/migrations). Same path from src/ and dist/. */
export const migrationsFolder = path.resolve(import.meta.dirname, "..", "migrations");

export interface DatabaseOptions {
  /** postgres:// connection string. */
  url: string;
  /** Pool size per process. Cloud Run: keep max instances × max <= the Cloud SQL connection limit. */
  maxConnections?: number;
  /** Shown in pg_stat_activity, e.g. `fleettrust-api`. */
  applicationName?: string;
}

export interface DatabaseHandle {
  db: Database;
  /** Lightweight connectivity check for readiness probes. */
  ping(): Promise<void>;
  close(): Promise<void>;
}

export function createDatabase(options: DatabaseOptions): DatabaseHandle {
  const pool = new pg.Pool({
    connectionString: options.url,
    max: options.maxConnections ?? 10,
    application_name: options.applicationName ?? "fleettrust",
    // Fail fast instead of hanging requests when the database is unreachable.
    connectionTimeoutMillis: 5_000,
    idleTimeoutMillis: 30_000,
  });
  const db = drizzle(pool, { schema });
  return {
    db,
    async ping() {
      await pool.query("SELECT 1");
    },
    async close() {
      await pool.end();
    },
  };
}

/** Applies pending migrations through node-postgres. Uses a single connection. */
export async function runMigrations(url: string): Promise<void> {
  const client = new pg.Client({ connectionString: url, application_name: "fleettrust-migrate" });
  await client.connect();
  try {
    await migrateNodePg(drizzle(client), { migrationsFolder });
  } finally {
    await client.end();
  }
}
