import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

export type EnvMap = Map<string, string>;

/** Minimal dotenv parser: KEY=VALUE lines, # comments, optional surrounding quotes. */
export function parseEnvFile(text: string): EnvMap {
  const env: EnvMap = new Map();
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line === "" || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (/^(["']).*\1$/.test(value)) value = value.slice(1, -1);
    env.set(key, value);
  }
  return env;
}

/** URL-safe random secret with no characters that need escaping in URLs, shells or YAML. */
export function generateSecret(bytes = 24): string {
  return randomBytes(bytes).toString("base64url");
}

/** Plain (non-derived) settings and how to produce each one's initial value. */
const baseSettings: readonly (readonly [key: string, initial: () => string])[] = [
  ["POSTGRES_USER", () => "fleettrust"],
  ["POSTGRES_PASSWORD", generateSecret],
  ["POSTGRES_DB", () => "fleettrust"],
  ["POSTGRES_TEST_DB", () => "fleettrust_test"],
  ["POSTGRES_PORT", () => "5432"],
  ["REDIS_PASSWORD", generateSecret],
  ["REDIS_PORT", () => "6379"],
  ["MAILPIT_UI_USER", () => "fleettrust"],
  ["MAILPIT_UI_PASSWORD", generateSecret],
  ["MAILPIT_SMTP_PORT", () => "1025"],
  ["MAILPIT_UI_PORT", () => "8025"],
];

function required(env: EnvMap, key: string): string {
  const value = env.get(key);
  if (value === undefined || value === "") throw new Error(`${key} is missing`);
  return value;
}

/** Connection strings computed from the base settings, always kept in sync with them. */
export function deriveConnectionStrings(env: EnvMap): EnvMap {
  const user = encodeURIComponent(required(env, "POSTGRES_USER"));
  const password = encodeURIComponent(required(env, "POSTGRES_PASSWORD"));
  const pgPort = required(env, "POSTGRES_PORT");
  const redisPassword = encodeURIComponent(required(env, "REDIS_PASSWORD"));
  const pgBase = `postgresql://${user}:${password}@127.0.0.1:${pgPort}`;
  return new Map([
    ["DATABASE_URL", `${pgBase}/${encodeURIComponent(required(env, "POSTGRES_DB"))}`],
    ["DATABASE_URL_TEST", `${pgBase}/${encodeURIComponent(required(env, "POSTGRES_TEST_DB"))}`],
    ["REDIS_URL", `redis://:${redisPassword}@127.0.0.1:${required(env, "REDIS_PORT")}/0`],
    ["SMTP_URL", `smtp://127.0.0.1:${required(env, "MAILPIT_SMTP_PORT")}`],
  ]);
}

export interface EnsureResult {
  created: boolean;
  /** Names (never values) of settings that were added. */
  added: string[];
}

const header = [
  "# Generated by `pnpm infra:env`. Local development only; git-ignored. Never commit or share.",
  "# Edit freely: existing values are never overwritten. Delete a line to regenerate it.",
  "# Changing passwords after the first `pnpm infra:up` also requires `pnpm infra:destroy` (data loss).",
];

/**
 * Creates the local env file, or adds any settings missing from an existing one.
 * Existing values are preserved; derived connection strings are recomputed from them.
 */
export function ensureLocalEnvFile(filePath: string): EnsureResult {
  const created = !existsSync(filePath);
  const env = created ? new Map<string, string>() : parseEnvFile(readFileSync(filePath, "utf8"));
  const added: string[] = [];

  for (const [key, initial] of baseSettings) {
    if (!env.get(key)) {
      env.set(key, initial());
      added.push(key);
    }
  }
  for (const [key, value] of deriveConnectionStrings(env)) {
    if (env.get(key) !== value) {
      if (!env.has(key)) added.push(key);
      env.set(key, value);
    }
  }

  const knownKeys = new Set([
    ...baseSettings.map(([key]) => key),
    ...deriveConnectionStrings(env).keys(),
  ]);
  const extra = [...env.keys()].filter((key) => !knownKeys.has(key));
  const lines = [
    ...header,
    "",
    ...baseSettings.map(([key]) => `${key}=${required(env, key)}`),
    "",
    "# Derived connection strings (recomputed on every run)",
    ...[...deriveConnectionStrings(env)].map(([key, value]) => `${key}=${value}`),
    ...(extra.length > 0
      ? ["", "# Custom settings", ...extra.map((key) => `${key}=${env.get(key) ?? ""}`)]
      : []),
    "",
  ];
  // 0o600: readable by the current user only (ignored on Windows, where ACLs apply instead).
  writeFileSync(filePath, lines.join("\n"), { encoding: "utf8", mode: 0o600 });
  return { created, added };
}
